/* ============================================================================
   V004__transaction_photos.sql
   MH02 Asset Report Portal - Transaction photo metadata

   Source of truth : docs/PHASE2_DATABASE_DESIGN.md (Revision 9), sections 3.12
                     and 4.
   Table created   : transaction_photos
   Depends on      : V003 (activities)
   Target database : db_asset_report (SQL Server)

   STATUS: DRAFT FOR REVIEW. This file has NOT been executed.

   Rules followed (design section 8):
   - Forward-only. Creates objects only: no DROP, no ALTER of existing objects,
     no data changes, no seed rows.
   - Runs as one SQL transaction (all or nothing).
   - Fails (and rolls back) if the target table already exists or V003's
     activities table is missing.
   - Does NOT insert its own row into schema_migrations (the runner does).
   - Contains no GRANT/DENY (the application login does not exist yet).
   - No GO separators (single batch for the Node.js `mssql` driver).

   Photo design notes:
   - Photo bytes NEVER enter SQL Server: this table holds metadata and a
     relative file path only (no VARBINARY column).
   - photo_id is generated by the service when the file is received, BEFORE the
     SQL transaction, and supplied on INSERT. There is deliberately NO default
     on photo_id.
   - storage_path is the FINAL location under PHOTO_STORAGE_ROOT, relative,
     following the pattern photos/{yyyy}/{mm}/{photo_id}.{ext}. The pattern,
     the allowed formats (JPEG, PNG, WebP), MIME type, magic bytes, size and
     SHA-256 are validated by the service, not by this file.
   - No maximum photo size and no retention/expiry column: P4 is still pending.
   - No staging or reconciliation tables: staging state lives in the file
     system and is derived from photo_id (design 3.12).

   Column types NOT specified by the design are TENTATIVE and open to review:
   original_filename, mime_type, size_bytes, sha256, uploaded_by, uploaded_at.
   ============================================================================ */

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRY
    BEGIN TRANSACTION;

    /* ---- Safety guards ---------------------------------------------------- */
    IF DB_NAME() <> N'db_asset_report'
        THROW 50001, N'V004: wrong database context. Expected db_asset_report.', 1;

    IF EXISTS (
        SELECT 1
        FROM sys.tables
        WHERE schema_id = SCHEMA_ID(N'dbo')
          AND name = N'transaction_photos'
    )
        THROW 50002, N'V004: transaction_photos already exists. Nothing was changed.', 1;

    IF NOT EXISTS (
        SELECT 1
        FROM sys.tables
        WHERE schema_id = SCHEMA_ID(N'dbo')
          AND name = N'activities'
    )
        THROW 50003, N'V004: required table dbo.activities is missing. Apply V003 first.', 1;

    /* ---- 3.12 transaction_photos ------------------------------------------ */
    CREATE TABLE dbo.transaction_photos (
        photo_id           UNIQUEIDENTIFIER NOT NULL,           -- supplied by the service on INSERT; NO default
        activity_id        UNIQUEIDENTIFIER NOT NULL,
        slot_key           VARCHAR(40)      NOT NULL,           -- e.g. 'mh02_installed'; allowed values validated per activity type by the service
        caption            NVARCHAR(200)    NULL,
        storage_provider   VARCHAR(20)      NOT NULL
            CONSTRAINT DF_transaction_photos_storage_provider DEFAULT ('local_fs'),
        storage_path       NVARCHAR(500)    NOT NULL,           -- FINAL relative path: photos/{yyyy}/{mm}/{photo_id}.{ext}
        original_filename  NVARCHAR(255)    NULL,               -- tentative type
        mime_type          VARCHAR(50)      NOT NULL,           -- tentative type; JPEG/PNG/WebP validated by the service
        size_bytes         BIGINT           NOT NULL,           -- tentative type; no maximum fixed (P4 pending)
        sha256             CHAR(64)         NOT NULL,           -- tentative type; hex digest computed by the service
        uploaded_by        UNIQUEIDENTIFIER NULL,               -- tentative type; no FK (not specified by the design)
        uploaded_at        DATETIME2(0)     NOT NULL            -- tentative type; set when the file is received
            CONSTRAINT DF_transaction_photos_uploaded_at DEFAULT (SYSUTCDATETIME()),
        CONSTRAINT PK_transaction_photos PRIMARY KEY (photo_id),
        CONSTRAINT FK_transaction_photos_activities
            FOREIGN KEY (activity_id) REFERENCES dbo.activities (activity_id) ON DELETE CASCADE,
        CONSTRAINT UQ_transaction_photos_activity_slot UNIQUE (activity_id, slot_key),
        /* storage_path must be a non-blank relative path: not empty and not only
           spaces, no leading '/' or '\', no drive letter or URI scheme (':'),
           and no '..' segment. */
        CONSTRAINT CK_transaction_photos_storage_path_relative
            CHECK (LEN(LTRIM(RTRIM(storage_path))) > 0
               AND storage_path NOT LIKE '/%'
               AND storage_path NOT LIKE '\%'
               AND storage_path NOT LIKE '%:%'
               AND storage_path NOT LIKE '%..%')
    );

    /* Supports the bounded keyset pagination of the committed-photo integrity
       check (design 3.12): ordered by (uploaded_at, photo_id). */
    CREATE NONCLUSTERED INDEX IX_transaction_photos_integrity_cursor
        ON dbo.transaction_photos (uploaded_at, photo_id);

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0
        ROLLBACK TRANSACTION;
    THROW;
END CATCH;
