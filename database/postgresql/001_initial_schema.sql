-- Draft for an empty db_asset_report database. Review and test before applying.
-- Does not import SQL Server data, create users, or seed reference data.
BEGIN;

DO $$
BEGIN
    IF current_database() <> 'db_asset_report' THEN
        RAISE EXCEPTION 'Expected database db_asset_report';
    END IF;
END $$;

CREATE TABLE sites (
    site_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_code varchar(30) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    time_zone_id varchar(50) NOT NULL,
    is_operating_district boolean NOT NULL DEFAULT true,
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE roles (
    role_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code varchar(30) NOT NULL UNIQUE,
    name varchar(60) NOT NULL
);

CREATE TABLE equipment_types (
    equipment_type_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(40) NOT NULL UNIQUE
);

CREATE TABLE device_statuses (
    status_id integer PRIMARY KEY,
    code varchar(30) NOT NULL UNIQUE,
    label varchar(50),
    is_in_stock boolean
);

CREATE TABLE import_batches (
    batch_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    source_name varchar(200) NOT NULL,
    data_source varchar(20) NOT NULL,
    imported_by uuid,
    imported_at timestamptz DEFAULT CURRENT_TIMESTAMP,
    row_count integer,
    status varchar(20),
    notes varchar(1000)
);

CREATE TABLE users (
    user_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    nrp varchar(30) NOT NULL UNIQUE,
    name varchar(120) NOT NULL,
    email varchar(150),
    phone varchar(30),
    role_id integer NOT NULL REFERENCES roles(role_id),
    site_id integer REFERENCES sites(site_id),
    password_hash varchar(255) NOT NULL,
    status varchar(10) NOT NULL CHECK (status IN ('active', 'inactive')),
    failed_login_count integer,
    locked_until timestamptz,
    last_login_at timestamptz,
    data_source varchar(20) NOT NULL CHECK (data_source IN ('app', 'dev_seed')),
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
    created_by uuid,
    updated_at timestamptz,
    updated_by uuid
);

CREATE TABLE auth_sessions (
    session_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    token_hash char(64) NOT NULL UNIQUE,
    user_id uuid NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    ip_address varchar(45),
    user_agent varchar(500)
);

CREATE TABLE lookup_values (
    lookup_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category varchar(30) NOT NULL CHECK (category IN ('shift', 'source_power', 'spm_version', 'area', 'group_leader')),
    code varchar(60) NOT NULL,
    label varchar(120) NOT NULL,
    site_id integer REFERENCES sites(site_id),
    sort_order integer,
    is_active boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX ux_lookup_values_site ON lookup_values(category, label, site_id) WHERE site_id IS NOT NULL;
CREATE UNIQUE INDEX ux_lookup_values_global ON lookup_values(category, label) WHERE site_id IS NULL;

CREATE TABLE fleet_units (
    unit_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    unit_no varchar(30) NOT NULL UNIQUE,
    equipment_type_id integer NOT NULL REFERENCES equipment_types(equipment_type_id),
    egi varchar(60),
    is_egi_confirmed boolean NOT NULL DEFAULT false,
    site_id integer NOT NULL REFERENCES sites(site_id),
    is_active boolean NOT NULL DEFAULT true,
    data_source varchar(20) NOT NULL CHECK (data_source IN ('dev_seed', 'import', 'manual')),
    import_batch_id uuid REFERENCES import_batches(batch_id)
);

CREATE TABLE devices (
    device_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    device_code varchar(40) NOT NULL UNIQUE,
    serial_number varchar(80) NOT NULL,
    status_id integer NOT NULL REFERENCES device_statuses(status_id),
    site_id integer NOT NULL REFERENCES sites(site_id),
    current_location_site_id integer REFERENCES sites(site_id),
    current_unit_id uuid REFERENCES fleet_units(unit_id),
    health_check_status varchar(15) NOT NULL DEFAULT 'not_checked' CHECK (health_check_status IN ('complete', 'incomplete', 'not_checked')),
    last_maintenance_date date,
    notes varchar(500),
    data_source varchar(20) NOT NULL CHECK (data_source IN ('dev_seed', 'import', 'manual')),
    import_batch_id uuid REFERENCES import_batches(batch_id),
    is_deleted boolean NOT NULL DEFAULT false,
    deleted_at timestamptz,
    deleted_by uuid,
    row_version bigint NOT NULL DEFAULT 1,
    created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
    created_by uuid,
    updated_at timestamptz,
    updated_by uuid,
    CHECK ((status_id = 1 AND current_unit_id IS NOT NULL) OR (status_id <> 1 AND current_unit_id IS NULL))
);
CREATE UNIQUE INDEX ux_devices_serial_number ON devices(serial_number) WHERE NOT is_deleted;
CREATE UNIQUE INDEX ux_devices_current_unit_id ON devices(current_unit_id) WHERE current_unit_id IS NOT NULL;

CREATE TABLE activities (
    activity_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    activity_type varchar(15) NOT NULL CHECK (activity_type IN ('installation', 'replacement', 'removal', 'troubleshoot')),
    form_number varchar(30) NOT NULL UNIQUE,
    site_id integer NOT NULL REFERENCES sites(site_id),
    unit_id uuid REFERENCES fleet_units(unit_id),
    started_at timestamptz NOT NULL,
    finished_at timestamptz NOT NULL,
    time_zone_id varchar(50) NOT NULL,
    start_utc_offset_minutes smallint NOT NULL CHECK (start_utc_offset_minutes BETWEEN -720 AND 840),
    finish_utc_offset_minutes smallint NOT NULL CHECK (finish_utc_offset_minutes BETWEEN -720 AND 840),
    duration_minutes integer NOT NULL,
    shift varchar(10),
    technician_user_id uuid REFERENCES users(user_id),
    technician_name varchar(120),
    technician_nrp varchar(30),
    group_leader varchar(120),
    remarks varchar(1000),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by uuid,
    updated_at timestamptz,
    updated_by uuid,
    row_version bigint NOT NULL DEFAULT 1,
    CHECK (finished_at >= started_at),
    CHECK (duration_minutes = (floor(extract(epoch FROM finished_at) / 60) - floor(extract(epoch FROM started_at) / 60))::integer)
);
CREATE INDEX ix_activities_site_started ON activities(site_id, started_at DESC);
CREATE INDEX ix_activities_type_started ON activities(activity_type, started_at);

CREATE TABLE activity_devices (
    activity_id uuid NOT NULL REFERENCES activities(activity_id) ON DELETE CASCADE,
    device_id uuid NOT NULL REFERENCES devices(device_id),
    role varchar(10) NOT NULL CHECK (role IN ('subject', 'old', 'new')),
    before_status_id integer NOT NULL REFERENCES device_statuses(status_id),
    after_status_id integer NOT NULL REFERENCES device_statuses(status_id),
    before_unit_id uuid REFERENCES fleet_units(unit_id),
    after_unit_id uuid REFERENCES fleet_units(unit_id),
    before_location_site_id integer REFERENCES sites(site_id),
    after_location_site_id integer REFERENCES sites(site_id),
    before_last_maintenance_date date,
    after_last_maintenance_date date,
    PRIMARY KEY (activity_id, device_id)
);
CREATE INDEX ix_activity_devices_device_activity ON activity_devices(device_id, activity_id);

CREATE TABLE installation_details (
    activity_id uuid PRIMARY KEY REFERENCES activities(activity_id) ON DELETE CASCADE,
    equipment_type_id integer,
    egi varchar(60),
    source_power varchar(60),
    spm_version varchar(60),
    area varchar(60),
    location_detail varchar(200),
    ip_address varchar(45),
    ip_cpe varchar(45),
    ip_vhms varchar(45),
    notes varchar(1000)
);

CREATE TABLE replacement_details (
    activity_id uuid PRIMARY KEY REFERENCES activities(activity_id) ON DELETE CASCADE,
    old_final_status_id integer NOT NULL REFERENCES device_statuses(status_id) CHECK (old_final_status_id IN (2, 3, 4)),
    source_power varchar(60),
    spm_version varchar(60),
    area varchar(60),
    location_detail varchar(200),
    ip_address varchar(45),
    ip_cpe varchar(45),
    ip_vhms varchar(45)
);

CREATE TABLE removal_details (
    activity_id uuid PRIMARY KEY REFERENCES activities(activity_id) ON DELETE CASCADE,
    reason varchar(200) NOT NULL,
    reason_detail varchar(1000),
    final_status_id integer NOT NULL REFERENCES device_statuses(status_id) CHECK (final_status_id IN (2, 3, 4))
);

CREATE TABLE troubleshoot_details (
    activity_id uuid PRIMARY KEY REFERENCES activities(activity_id) ON DELETE CASCADE,
    component_type varchar(20) CHECK (component_type IN ('MH02 Device', 'GPS/Antenna', 'Camera', 'Wiring', 'Speaker', 'SPM', 'CPE', 'Firmware')),
    issue varchar(1000) NOT NULL,
    action_taken varchar(1000) NOT NULL,
    health_check_result varchar(10) CHECK (health_check_result IN ('Pass', 'Fail', 'Verified', 'Pending'))
);

CREATE TABLE form_sequences (
    activity_type varchar(15) NOT NULL,
    year_month char(6) NOT NULL,
    last_number integer NOT NULL,
    PRIMARY KEY (activity_type, year_month)
);

CREATE TABLE idempotency_keys (
    user_id uuid NOT NULL REFERENCES users(user_id),
    idempotency_key varchar(64) NOT NULL,
    activity_type varchar(15) NOT NULL,
    request_hash char(64) NOT NULL,
    activity_id uuid,
    form_number varchar(30),
    device_id uuid REFERENCES devices(device_id),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, idempotency_key),
    CHECK ((activity_type <> 'device' AND device_id IS NULL AND ((activity_id IS NULL AND form_number IS NULL) OR (activity_id IS NOT NULL AND form_number IS NOT NULL))) OR (activity_type = 'device' AND activity_id IS NULL AND form_number IS NULL))
);

CREATE TABLE transaction_photos (
    photo_id uuid PRIMARY KEY,
    activity_id uuid NOT NULL REFERENCES activities(activity_id) ON DELETE CASCADE,
    slot_key varchar(40) NOT NULL,
    caption varchar(200),
    storage_provider varchar(20) NOT NULL DEFAULT 'local_fs',
    storage_path varchar(500) NOT NULL CHECK (btrim(storage_path) <> '' AND left(storage_path, 1) NOT IN ('/', E'\\') AND position(':' IN storage_path) = 0 AND position('..' IN storage_path) = 0),
    original_filename varchar(255),
    mime_type varchar(50) NOT NULL,
    size_bytes bigint NOT NULL,
    sha256 char(64) NOT NULL,
    uploaded_by uuid,
    uploaded_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (activity_id, slot_key)
);
CREATE INDEX ix_transaction_photos_integrity_cursor ON transaction_photos(uploaded_at, photo_id);

CREATE TABLE audit_log (
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor_user_id uuid REFERENCES users(user_id),
    actor_name varchar(120),
    site_id integer REFERENCES sites(site_id),
    table_name varchar(30) NOT NULL CHECK (table_name IN ('installation', 'replacement', 'removal', 'troubleshoot', 'device', 'user_management')),
    record_id varchar(60) NOT NULL,
    entity_id uuid NOT NULL,
    operation varchar(6) NOT NULL CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    old_values jsonb,
    new_values jsonb,
    change_group_id uuid NOT NULL,
    ip_address varchar(45),
    request_id varchar(64),
    action varchar(30) NOT NULL CHECK (action IN ('device_register', 'device_update', 'device_override', 'device_archive', 'transaction_create', 'transaction_update', 'transaction_delete', 'user_create', 'user_update', 'user_deactivate', 'user_password_reset')),
    reason varchar(500),
    CHECK (action <> 'device_override' OR (reason IS NOT NULL AND btrim(reason) <> ''))
);
CREATE INDEX ix_audit_log_site_occurred ON audit_log(site_id, occurred_at DESC);

CREATE TABLE device_events (
    event_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    device_id uuid NOT NULL REFERENCES devices(device_id),
    event_type varchar(30) NOT NULL CHECK (event_type IN ('registered', 'details_updated', 'soft_deleted', 'transaction_deleted', 'device_override')),
    occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actor_user_id uuid NOT NULL REFERENCES users(user_id),
    actor_name varchar(120),
    site_id integer NOT NULL,
    audit_id bigint NOT NULL UNIQUE REFERENCES audit_log(audit_id),
    summary varchar(200),
    reason varchar(500),
    before_status_id integer REFERENCES device_statuses(status_id),
    after_status_id integer REFERENCES device_statuses(status_id),
    before_unit_id uuid REFERENCES fleet_units(unit_id),
    after_unit_id uuid REFERENCES fleet_units(unit_id),
    source_activity_id uuid,
    source_activity_type varchar(15) CHECK (source_activity_type IN ('installation', 'replacement', 'removal', 'troubleshoot')),
    source_form_number varchar(30),
    source_role varchar(10) CHECK (source_role IN ('subject', 'old', 'new')),
    source_started_at_local timestamp,
    source_time_zone_id varchar(50),
    CHECK ((event_type = 'device_override' AND reason IS NOT NULL AND btrim(reason) <> '' AND before_status_id IS NOT NULL AND after_status_id IS NOT NULL) OR (event_type <> 'device_override' AND before_status_id IS NULL AND after_status_id IS NULL AND before_unit_id IS NULL AND after_unit_id IS NULL)),
    CHECK ((event_type = 'transaction_deleted' AND source_activity_id IS NOT NULL AND source_activity_type IS NOT NULL AND source_form_number IS NOT NULL AND source_role IS NOT NULL AND source_started_at_local IS NOT NULL AND source_time_zone_id IS NOT NULL) OR (event_type <> 'transaction_deleted' AND source_activity_id IS NULL AND source_activity_type IS NULL AND source_form_number IS NULL AND source_role IS NULL AND source_started_at_local IS NULL AND source_time_zone_id IS NULL))
);
CREATE UNIQUE INDEX ux_device_events_registered ON device_events(device_id) WHERE event_type = 'registered';
CREATE UNIQUE INDEX ux_device_events_deleted ON device_events(device_id, source_activity_id) WHERE event_type = 'transaction_deleted';

CREATE FUNCTION reject_history_changes() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only', TG_TABLE_NAME;
END $$;
CREATE TRIGGER audit_log_append_only BEFORE UPDATE OR DELETE ON audit_log FOR EACH ROW EXECUTE FUNCTION reject_history_changes();
CREATE TRIGGER device_events_append_only BEFORE UPDATE OR DELETE ON device_events FOR EACH ROW EXECUTE FUNCTION reject_history_changes();

CREATE FUNCTION update_row_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.row_version := OLD.row_version + 1;
    RETURN NEW;
END $$;

CREATE FUNCTION protect_activity_site_zone() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.site_id <> OLD.site_id OR NEW.time_zone_id <> OLD.time_zone_id THEN
        RAISE EXCEPTION 'Activity site and time zone cannot be changed';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER devices_row_version BEFORE UPDATE ON devices FOR EACH ROW EXECUTE FUNCTION update_row_version();
CREATE TRIGGER activities_row_version BEFORE UPDATE ON activities FOR EACH ROW EXECUTE FUNCTION update_row_version();
CREATE TRIGGER activities_site_zone_immutable BEFORE UPDATE ON activities FOR EACH ROW EXECUTE FUNCTION protect_activity_site_zone();

COMMIT;